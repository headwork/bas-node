/**
 * 스크립트와 Node 의 계약 — 종료코드. (#P202609_002 [D10])
 *
 * 정본은 `docs/design/배포/06_배포_스크립트_규약.md` §4 이고, 이 파일이 그 사본이다.
 * **사본이 하나여야 한다** — 이 과제가 없애려는 병이 바로 같은 표가 여러 곳에 적히는 것이다.
 *
 * 출력을 파싱하지 않는 이유가 여기 있다. `appcmd` 는 "이미 멈춤" 에도 0 이 아닌 코드를 내고
 * 그 메시지는 **서버 로캘**을 따른다(한글 Windows 면 한글). 스크립트가 코드로 정규화하면
 * Node 는 로캘을 모르고도 판정할 수 있다.
 */

/** 어느 스크립트에서나 같은 뜻인 것들. */
const COMMON = {
  2: '스크립트에 넘긴 값이 없거나 잘못되었습니다',
  3: '권한 부족 - 관리자 권한으로 실행해야 합니다',
  4: '대상을 찾을 수 없습니다 (사이트·서비스 이름, 또는 어댑터 스크립트가 없음)'
};

/** `webserver_<type>.bat` — 정지·기동·상태. */
const WEBSERVER = {
  ...COMMON,
  1: '알 수 없는 실패',
  5: '실패했고 되돌리지도 못했습니다 - 라이브 폴더가 없습니다. 사람이 고쳐야 합니다',
  // `status` 에서만 나온다. 실패가 아니라 답이다.
  6: '웹서버가 실행 중이 아닙니다'
};

/**
 * `patch.bat` — 정적 배포. 바뀐 파일만 라이브에 덮어쓴다. 정지도 스왑도 없다.
 *
 * ⚠️ `6` 은 **성공**이다. 서버가 멈춰 있어 시작했다는 뜻이고, 그때만 헬스체크를 한다.
 *    출력을 파싱하지 않으려고 코드로 받는다.
 */
const PATCH = {
  ...COMMON,
  1: '정적 파일 복사 실패 - 일부 파일은 이미 라이브에 들어갔을 수 있습니다. 다음 배포가 같은 범위를 다시 복사합니다',
  4: '라이브 폴더를 찾을 수 없습니다 (또는 웹서버 대상·어댑터 스크립트가 없음)',
  6: '복사함 - 웹서버가 멈춰 있어 시작했습니다'
};

/**
 * `deploy.bat` — 정지 → 백업 → 스왑 → 시작.
 *
 * ⚠️ `1` 과 `5` 의 차이가 **이 스크립트에서 가장 중요한 갈림길**이다.
 *    `1` 은 라이브가 살아 있다(옮기기 전이거나, 되돌렸다). 사람이 할 일이 없다.
 *    `5` 는 라이브가 **없다**. 백업만 남아 있고, 그것이 이전 빌드의 유일한 사본이다.
 */
const DEPLOY = {
  ...COMMON,
  1: '배포 실패 - 라이브는 이전 빌드로 살아 있습니다',
  5: '배포에 실패했고 되돌리지도 못했습니다 - 라이브 폴더가 없습니다'
};

/**
 * `rollback.bat` — 백업본 복귀.
 *
 * `4` 의 첫 번째 뜻이 **백업 폴더가 없다**이다. 이력에는 남아 있는데 폴더가 없으면
 * 사람이 지운 것이고, 다음 백업으로 넘어가면 의도한 것보다 더 되돌아간다.
 */
const ROLLBACK = {
  ...COMMON,
  1: '롤백 실패 - 라이브는 그대로입니다',
  4: '백업 폴더를 찾을 수 없습니다 (또는 어댑터 스크립트가 없음). 이력에는 남아 있다면 누가 지웠는지 확인하십시오',
  5: '롤백에 실패했고 라이브 폴더가 없습니다 - 사람이 고쳐야 합니다'
};

/** 표에 없는 코드도 숫자로는 말해 준다. 조용히 0 처럼 넘기지 않는다. */
function reasonFor(table, code) {
  return table[code] || `알 수 없는 종료코드 ${code}`;
}

module.exports = { COMMON, WEBSERVER, DEPLOY, ROLLBACK, PATCH, reasonFor };
